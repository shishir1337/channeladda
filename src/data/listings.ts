import type { PlatformId } from "@/data/platforms";

export type ListingTag = "featured" | "hot" | "new" | "ending";

export type Listing = {
  id: string;
  /** Human-readable URL key. */
  slug: string;
  platform: PlatformId;
  handle: string;
  title: string;
  /** Subscribers / followers / members / monthly visits. */
  audience: number;
  monetized: boolean;
  /** Verified USD per month at handover. 0 when not monetized. */
  monthlyRevenue: number;
  niche: string;
  country: string;
  /** Percentage, one decimal. */
  engagement: number;
  ageYears: number;
  /** Always USD; converted at render by the currency context. */
  price: number;
  /** Present when the seller has dropped the price since listing. */
  wasPrice?: number;
  ownershipVerified: boolean;
  /// Artwork URLs, supplied by the seller in production.
  coverUrl: string;
  avatarUrl: string;
  /** Slug into the sellers table. */
  sellerSlug: string;
  /**
   * The seller as a buyer sees them on a card.
   *
   * These used to be looked up in a static fixture by slug, which meant any
   * seller the fixtures did not know about — that is, every real one — made
   * the card throw and took the whole page down with it.
   */
  sellerName: string;
  sellerRating: number;
  sellerSales: number;
  watching: number;
  /** Days since the listing went live — drives "just listed" sorting. */
  listedDaysAgo: number;
  tag?: ListingTag;
};

/**
 * Seed input. The database is the source of truth at runtime; these fixtures
 * exist only to populate it, so they carry no artwork URLs — the seed derives
 * those from the id below.
 */
/**
 * Seed input. Artwork and the seller display fields are not part of it: those
 * are derived at runtime from the database, not authored in a fixture.
 */
