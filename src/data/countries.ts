const BY_LOWER = new Map(COUNTRIES.map((name) => [name.toLowerCase(), name]));

/** The list’s own spelling of a country, or null when it is not one. */
export function canonicalCountry(input: string): string | null {
  return BY_LOWER.get(input.trim().replace(/\s+/g, " ").toLowerCase()) ?? null;
}
